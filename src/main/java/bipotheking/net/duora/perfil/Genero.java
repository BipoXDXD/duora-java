package bipotheking.net.duora.perfil;

/**
 * O gênero da pessoa e os que ela quer conhecer no namoro. Dado sensível (LGPD, art. 11): só com
 * consentimento e nunca visível a terceiros. {@link #OUTRO} vem com descrição livre.
 */
public enum Genero {
  MULHER,
  HOMEM,
  PESSOA_NAO_BINARIA,
  OUTRO
}
